"""AI Summary tab: Claude rewrites notes into professional wording.

The generated text is placed into editable fields; the inspector reviews and
edits it before it goes on the report. Claude never sets PASS / FAIL.
"""

from __future__ import annotations

import streamlit as st

from config import settings
from services import claude_service
from services.calculation_service import evaluate_report
from services.validation_service import validate_report
from ui.evaluation_view import show_validation
from ui.state import report_from_state


def _generate() -> None:
    """Button callback: runs before widgets are drawn, so it may set their values."""
    st.session_state.pop("ai_error", None)
    st.session_state.pop("ai_notice", None)
    report = report_from_state()
    validation = validate_report(report)
    if not validation.is_valid:
        st.session_state["ai_error"] = "Fix the validation errors (see the Inspection & Report tab) first."
        st.session_state["last_validation"] = validation
        return
    evaluation = evaluate_report(report)
    try:
        wording = claude_service.generate_wording(report, evaluation)
    except claude_service.ClaudeServiceError as e:
        st.session_state["ai_error"] = str(e)
        return
    st.session_state["ai.summary"] = wording.summary
    st.session_state["ai.microstructure"] = wording.microstructure
    st.session_state["ai.remarks"] = wording.remarks
    st.session_state["ai_notice"] = "AI wording generated. Review and edit it before generating the report."


def _clear() -> None:
    for key in ("ai.summary", "ai.microstructure", "ai.remarks"):
        st.session_state[key] = ""
    st.session_state.pop("ai_notice", None)


def render_ai_summary() -> None:
    st.subheader("AI Summary")
    st.caption(
        "Claude converts your notes into concise professional wording. It does **not** perform "
        "calculations or decide PASS / FAIL — it is given the results calculated by Python and "
        "must not invent results, standards or criteria."
    )

    if not claude_service.is_configured():
        st.warning(
            f"`{settings.ANTHROPIC_API_KEY_ENV}` is not set, so AI wording is unavailable. "
            "Evaluation and report generation still work; you can type the summary manually below, "
            "or leave it empty to use an automatic factual summary."
        )

    c1, c2 = st.columns([1, 1])
    c1.button("Generate AI Summary", type="primary", icon="✨", on_click=_generate,
              width="stretch")
    c2.button("Clear AI text", on_click=_clear, width="stretch")

    if st.session_state.get("ai_error"):
        st.error(st.session_state["ai_error"])
        if "last_validation" in st.session_state and not st.session_state["last_validation"].is_valid:
            show_validation(st.session_state["last_validation"])
    if st.session_state.get("ai_notice"):
        st.success(st.session_state["ai_notice"])

    st.text_area("Inspection Summary (appears on the report)", key="ai.summary",
                 max_chars=settings.MAX_CHARS_SUMMARY, height=120,
                 help="Leave empty to use an automatic factual summary generated by Python.")

    raw_micro = st.session_state.get("metallography.microstructure") or "—"
    st.text_area("Microstructure wording (replaces the raw observation on the report)",
                 key="ai.microstructure", max_chars=settings.MAX_CHARS_OBSERVATION, height=90)
    st.caption(f"Inspector's original observation: {raw_micro}")

    raw_remarks = st.session_state.get("info.remarks") or "—"
    st.text_area("Remarks wording (replaces the raw remarks on the report)", key="ai.remarks",
                 max_chars=settings.MAX_CHARS_REMARKS, height=80)
    st.caption(f"Inspector's original remarks: {raw_remarks}")
